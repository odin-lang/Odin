#!/usr/bin/env python3
"""
Generates `core:sys/android` and the `vendor:android/*` packages from the Android NDK's headers.

The headers are read through the NDK's own clang (`-Xclang -ast-dump=json`), so no
libclang or Python packages are needed. clang also evaluates every constant (enum
values and object-like macros), and the NDK's stub libraries decide which library
each function is imported from and the API level it first appeared in.

Names are kept exactly as in C. Each header (or small group of headers) becomes one
Odin file. Every generated file starts with GENERATED_MARKER. Only files carrying it
are overwritten or deleted, so hand-written files next to them are never touched.
The `vendor:android/*` packages refer to `core:sys/android` for the types its headers define.

`--verify` compiles probes on both sides for every Android ABI and compares the size,
alignment and field offsets of every type and the value of every constant. It also
links every binding against the newest stub libraries.

Usage:
	python core/sys/android/_gen/generate.py [--ndk <path/to/ndk>] [--target <name>] [--verify]

The NDK path defaults to the ODIN_ANDROID_NDK environment variable. Without `--target`,
every target in TARGETS is generated.
"""

