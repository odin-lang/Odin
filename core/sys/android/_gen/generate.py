def verify(ndk, model, values, includes, odin, tmp):
	"""Compare every type layout and constant with clang, then link every binding."""
	pkg = model.target.package
	imp = model.target.import_path

	def is_opaque(t):
		"""Whether a typedef names an opaque record (C cannot size those), here or in a base package."""
		t = strip_const(resolve_typedef(model, t))
		names = set()
		for m in [model, *model.bases]:
			if t[0] == "tag" and f"{t[1]} {t[2]}" in m.tag_names:
				names.add(m.tag_names[f"{t[1]} {t[2]}"])
			elif t[0] == "named":
				names.add(t[1])
		return any(r.name in names and r.opaque for m in [model, *model.bases] for r in m.records.values())

	types = []   # (name, [field names])
	for out_file in model.files:
		for item in model.files[out_file]:
			if item[0] == "record" and not item[1].opaque:
				fields = [f for f, _, _, _ in item[1].fields if f]
				types.append((item[1].name, fields, f"{'union' if item[1].union else 'struct'}"))
			elif item[0] == "typedef":
				t = resolve_typedef(model, ("named", item[1]))
				if strip_const(t)[0] not in ("func",) and not (t[0] == "tag" and t[2] in ("__ANON__",)) and not is_opaque(t):
					types.append((item[1], [], None))
			elif item[0] == "enum" and item[2] and item[2] not in TABLE.BACKINGS:
				types.append((item[2], [], None))

	probes = []  # (symbol, odin expr, c expr)
	for name, fields, _ in types:
		c_name = model.c_spelling[name]
		probes.append((f"s__{name}", f"size_of({pkg}.{name})", f"sizeof({c_name})"))
		probes.append((f"a__{name}", f"align_of({pkg}.{name})", f"_Alignof({c_name})"))
		for f in fields:
			probes.append((f"o__{name}__{f}", f"offset_of({pkg}.{name}, {odin_ident(f)})", f"offsetof({c_name}, {f})"))
	for name, value in values.items():
		if model.const_sources[name][0] not in model.files:
			continue
		te = model.typed_consts.get(name)
		if te is None or name in te.untyped or (te.kind == "enum" and name in te.members):
			odin_name = f"{pkg}.{te.name}.{te.members[name]}" if te and name in te.members else f"{pkg}.{name}"
			expr = f"transmute(i64)u64({odin_name})" if value >= 2**63 else odin_name
			probes.append((f"c__{name}", expr, name))
		elif name not in te.dropped:
			# bit_sets and bit_fields, compared as their unsigned bits
			odin_value = f"{pkg}.{te.name}{{.{te.members[name]}}}" if name in te.members else f"{pkg}.{name}"
			bits = INT_BITS[te.backing]
			expr = f"i64(transmute(u32)({odin_value}))" if bits == 32 else f"transmute(i64)(transmute(u64)({odin_value}))"
			probes.append((f"c__{name}", expr, f"(unsigned {'int' if bits == 32 else 'long long'})({name})"))

	tmp = os.path.join(tmp, model.target.name)
	os.makedirs(tmp, exist_ok=True)

	ok = True
	for abi, triple in ABIS:
		level = ndk.api_levels(triple)[-1]

		odin_src = os.path.join(tmp, f"probe_{abi}")
		os.makedirs(odin_src, exist_ok=True)
		with open(os.path.join(odin_src, "probe.odin"), "w", encoding="utf-8", newline="\n") as f:
			f.write(f"package probe\n\nimport {pkg} \"{imp}\"\n\n")
			for sym, expr, _ in probes:
				f.write(f"@(export, link_name=\"{sym}\") {sym}: i64 = i64({expr})\n")
		ll_dir = os.path.join(tmp, f"probe_{abi}_ir")
		os.makedirs(ll_dir, exist_ok=True)
		env = dict(os.environ, ODIN_ANDROID_NDK=ndk.root)
		code, out, err = run([odin, "build", odin_src, f"-target:linux_{abi}", "-subtarget:android", "-build-mode:llvm-ir", "-use-single-module", "-no-entry-point", f"-out:{ll_dir}"], env=env)
		if code != 0:
			print(out + err)
			raise GenError(f"odin probe failed for {abi}")
		odin_vals = {}
		for fn in os.listdir(ll_dir):
			if fn.endswith(".ll"):
				with open(os.path.join(ll_dir, fn), encoding="utf-8", errors="replace") as f:
					for line in f:
						m = re.match(r'^@"?(\w+)"?\s*=.*?global i64 (-?\d+)', line)
						if m:
							odin_vals[m.group(1)] = int(m.group(2))

		c_path = os.path.join(tmp, f"probe_{abi}.c")
		with open(c_path, "w", encoding="utf-8", newline="\n") as f:
			f.write(translation_unit(includes))
			f.write("#include <stddef.h>\n")
			for sym, _, expr in probes:
				f.write(f"const long long {sym} = (long long)({expr});\n")
		c_ll = os.path.join(tmp, f"probe_{abi}_c.ll")
		code, out, err = run([ndk.clang, f"--target={triple}{level}", "-S", "-emit-llvm", "-w", "-o", c_ll, c_path])
		if code != 0:
			print(err[:4000])
			raise GenError(f"clang probe failed for {abi}")
		c_vals = {}
		with open(c_ll, encoding="utf-8") as f:
			for line in f:
				m = re.match(r"^@(\w+)\s*=.*?constant i64 (-?\d+)", line)
				if m:
					c_vals[m.group(1)] = int(m.group(2))

		bad = [(s, odin_vals.get(s), c_vals.get(s)) for s, _, _ in probes if odin_vals.get(s) != c_vals.get(s)]
		print(f"{model.target.name} {abi}: {len(probes)} probes, {len(bad)} mismatches")
		for s, o, c in bad[:200]:
			print(f"\t{s}: odin={o} c={c}")
		ok = ok and not bad

		# Link every function and variable against the newest stubs.
		link_src = os.path.join(tmp, f"link_{abi}")
		os.makedirs(link_src, exist_ok=True)
		with open(os.path.join(link_src, "link.odin"), "w", encoding="utf-8", newline="\n") as f:
			f.write(f"package link\n\nimport {pkg} \"{imp}\"\n\n")
			f.write("@(export, link_name=\"odin_android_refs\")\nrefs := [?]rawptr{\n")
			for out_file in model.files:
				for item in model.files[out_file]:
					if item[0] == "func":
						f.write(f"\trawptr({pkg}.{item[1]['name']}),\n")
					elif item[0] == "var":
						f.write(f"\trawptr(&{pkg}.{item[1]['name']}),\n")
			f.write("}\n")
		so = os.path.join(tmp, f"link_{abi}.so")
		code, out, err = run([odin, "build", link_src, f"-target:linux_{abi}", "-subtarget:android", f"-minimum-os-version:{level}", "-build-mode:shared", f"-out:{so}"], env=env)
		if code != 0:
			print(out + err)
			ok = False
		print(f"{model.target.name} {abi}: link {'ok' if code == 0 else 'FAILED'}")
	return ok


