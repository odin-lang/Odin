def align_lines(rows, indent):
	"""rows: [(left, sep, right, trailing)] -> lines with `sep` aligned."""
	width = max((len(r[0]) for r in rows), default=0)
	lines = []
	for left, sep, right, trailing in rows:
		line = f"{indent}{left}{' ' * (width - len(left))}{sep}{right}"
		if trailing:
			line += trailing
		lines.append(line.rstrip())
	return lines


def emit_record(ctx, rec, indent):
	head = "struct"
	if rec.union:
		head += " #raw_union"
	if rec.packed:
		head += " #packed"
	if rec.opaque:
		return f"{head} {{}}"
	rows = []
	for i, (fname, ftype, nested, node) in enumerate(rec.fields):
		if nested is not None:
			body = emit_record(ctx, nested, indent + "\t")
			if strip_const(ftype)[0] == "array":
				raise GenError(f"array of anonymous record in {rec.name}")
			if fname is None:
				rows.append(("using _", ": ", body + ",", None))
			else:
				rows.append((odin_ident(fname), ": ", body + ",", None))
			continue
		names = source_param_names(ctx.model, node, rec.header, ftype)
		rows.append((odin_ident(fname or f"_{i}"), ": ", odin_type(ctx, ftype, "field", names) + ",", None))
	lines = [f"{head} {{"]
	# Align the field types, but not across nested multi-line records.
	group = []
	for row in rows:
		if "\n" in row[2]:
			lines += align_lines(group, indent + "\t")
			group = []
			lines.append(f"{indent}\t{row[0]}: {row[2]}")
		else:
			group.append((row[0] + ":", " ", row[2], None))
	lines += align_lines(group, indent + "\t")
	lines.append(f"{indent}}}")
	return "\n".join(lines)


def emit_file(model, out_file, values, strings, ndk):
	ctx = Ctx(model, out_file)
	items = model.files[out_file]

	blocks = []
	funcs  = defaultdict(list)  # library -> [row]
	vars_  = defaultdict(list)

	emitted_consts = set()

	def const_rows(names):
		rows = []
		for name in names:
			if name in emitted_consts or model.constants.get(name, out_file) != out_file:
				continue
			if name in strings:
				rows.append((name, " :: ", strings[name], None))
			elif name in values:
				rows.append((name, " :: ", format_constant(name, values[name], model), None))
			else:
				continue
			emitted_consts.add(name)
		return rows

	def one_liner(name, rhs):
		# Runs of one-line declarations share one aligned block.
		if blocks and isinstance(blocks[-1], list):
			blocks[-1].append((name, " :: ", rhs, None))
		else:
			blocks.append([(name, " :: ", rhs, None)])

	for item in items:
		kind = item[0]
		if kind == "record":
			rec = item[1]
			body = emit_record(ctx, rec, "")
			if rec.note:
				blocks.append(f"// {rec.note}\n{rec.name} :: {body}")
			elif "\n" in body:
				blocks.append(f"{rec.name} :: {body}")
			else:
				one_liner(rec.name, body)

		elif kind == "typedef":
			_, name, t, node, header = item
			names = source_param_names(model, node, header, t)
			if strip_const(t)[0] == "func":
				one_liner(name, odin_proc_type(ctx, strip_const(t), names))
			else:
				one_liner(name, odin_type(ctx, t, "typedef", names))

		elif kind == "enum":
			_, node, name, consts = item
			lines = []
			if name:
				underlying = enum_underlying(ctx, node, consts, values)
				lines.append(f"{name} :: {underlying}")
				lines.append("")
			rows = const_rows(consts)
			lines += align_lines(rows, "")
			if rows or name:
				blocks.append("\n".join(lines).rstrip())

		elif kind == "func":
			_, node, lib, level = item
			ftype = parse_type(node["type"]["qualType"])
			if ftype[0] != "func":
				raise GenError(f"{node['name']} is not a function type")
			names = []
			for i, p in enumerate(n for n in node.get("inner", []) if n.get("kind") == "ParmVarDecl"):
				names.append(param_ident(p["name"]) if p.get("name") else f"_{i}")
			if len(names) != len(ftype[2]) or len(set(names)) != len(names):
				names = [f"_{i}" for i in range(len(ftype[2]))]
			no_return = any(a.get("kind") in ("NoReturnAttr", "C11NoReturnAttr", "CXX11NoReturnAttr") for a in node.get("inner", [])) or "noreturn" in node["type"]["qualType"]
			sig = odin_proc_type(ctx, ftype, names, no_return).replace('proc "c" ', "proc", 1)
			trailing = f" // API level {level}" if level and level > MIN_API_LEVEL else None
			funcs[lib].append((node["name"], " :: ", sig + " ---", trailing))

		elif kind == "var":
			_, node, lib = item
			vars_[lib].append((node["name"] + ":", " ", odin_type(ctx, parse_type(node["type"]["qualType"]), "field"), None))

	# Macros that belong to no enum, in source order.
	macro_names = [n for n, (f, src) in model.const_sources.items() if f == out_file and src[0] == "macro"]
	rows = const_rows(macro_names)
	if rows:
		blocks.append("\n".join(align_lines(rows, "")))

	libraries = model.target.libraries
	libs = sorted(set(funcs) | set(vars_), key=lambda l: list(libraries).index(l))
	for lib in libs:
		name, _ = libraries[lib]
		lines = ["@(default_calling_convention=\"c\")", f"foreign {name} {{"]
		if vars_[lib]:
			lines += align_lines(vars_[lib], "\t")
			if funcs[lib]:
				lines.append("")
		lines += align_lines(funcs[lib], "\t")
		lines.append("}")
		blocks.append("\n".join(lines))

	if not blocks:
		return None  # e.g. a header of only function-like macros

	headers = [h for h, f in model.target.headers if f == out_file]
	text = [GENERATED_MARKER]
	text.append(f"// Source: {', '.join(f'<{h}>' for h in headers)} (NDK {ndk.release}, {ndk.revision})")
	text.append("#+build linux")
	text.append(f"package {model.target.package}")
	text.append("")
	imports = sorted(model.imports[out_file])
	if imports:
		packages = {t.import_path: t.package for t in TARGETS}
		for imp in imports:
			# An import is named after its path's last element, not its package (`vendor:android/media` is `media`).
			pkg = packages.get(imp)
			if pkg and pkg != imp.rsplit("/", 1)[-1]:
				text.append(f"import {pkg} \"{imp}\"")
			else:
				text.append(f"import \"{imp}\"")
		text.append("")
	for lib in libs:
		name, path = libraries[lib]
		text.append(f"foreign import {name} \"{path}\"")
	if libs:
		text.append("")
	rendered = ["\n".join(align_lines(b, "")) if isinstance(b, list) else b for b in blocks]
	text.append("\n\n".join(b for b in rendered if b))
	return "\n".join(text).rstrip() + "\n"


def enum_underlying(ctx, node, consts, values):
	fixed = node.get("fixedUnderlyingType")
	if fixed:
		return odin_type(ctx, parse_type(fixed["qualType"]), "typedef")
	vals = [values[c] for c in consts if c in values]
	ctx.model.imports[ctx.out_file].add("core:c")
	if all(-2**31 <= v < 2**31 for v in vals):
		return "c.int"
	if all(0 <= v < 2**32 for v in vals):
		return "c.uint"
	return "i64"


#
# Verification
#

def verify(ndk, model, values, includes, odin, tmp):
	"""Compare every type layout and constant with clang, then link every binding."""
	pkg = model.target.package
	imp = model.target.import_path

	def is_opaque(t):
		"""Whether a typedef names an opaque record (C cannot size those), here or in a base package."""
		t = strip_const(resolve_typedef(model, t))
		names = set()
		for m in [model, *model.bases]:
			if t[0] == "tag" and f"{t[1]} {t[2]}" in m.tag_names:
				names.add(m.tag_names[f"{t[1]} {t[2]}"])
			elif t[0] == "named":
				names.add(t[1])
		return any(r.name in names and r.opaque for m in [model, *model.bases] for r in m.records.values())

	types = []   # (name, [field names])
	for out_file in model.files:
		for item in model.files[out_file]:
			if item[0] == "record" and not item[1].opaque:
				fields = [f for f, _, _, _ in item[1].fields if f]
				types.append((item[1].name, fields, f"{'union' if item[1].union else 'struct'}"))
			elif item[0] == "typedef":
				t = resolve_typedef(model, ("named", item[1]))
				if strip_const(t)[0] not in ("func",) and not (t[0] == "tag" and t[2] in ("__ANON__",)) and not is_opaque(t):
					types.append((item[1], [], None))
			elif item[0] == "enum" and item[2]:
				types.append((item[2], [], None))

	probes = []  # (symbol, odin expr, c expr)
	for name, fields, _ in types:
		c_name = model.c_spelling[name]
		probes.append((f"s__{name}", f"size_of({pkg}.{name})", f"sizeof({c_name})"))
		probes.append((f"a__{name}", f"align_of({pkg}.{name})", f"_Alignof({c_name})"))
		for f in fields:
			probes.append((f"o__{name}__{f}", f"offset_of({pkg}.{name}, {odin_ident(f)})", f"offsetof({c_name}, {f})"))
	for name, value in values.items():
		if model.const_sources[name][0] in model.files:
			expr = f"transmute(i64)u64({pkg}.{name})" if value >= 2**63 else f"{pkg}.{name}"
			probes.append((f"c__{name}", expr, name))

	tmp = os.path.join(tmp, model.target.name)
	os.makedirs(tmp, exist_ok=True)

	ok = True
	for abi, triple in ABIS:
		level = ndk.api_levels(triple)[-1]

		odin_src = os.path.join(tmp, f"probe_{abi}")
		os.makedirs(odin_src, exist_ok=True)
		with open(os.path.join(odin_src, "probe.odin"), "w", encoding="utf-8", newline="\n") as f:
			f.write(f"package probe\n\nimport {pkg} \"{imp}\"\n\n")
			for sym, expr, _ in probes:
				f.write(f"@(export, link_name=\"{sym}\") {sym}: i64 = i64({expr})\n")
		ll_dir = os.path.join(tmp, f"probe_{abi}_ir")
		os.makedirs(ll_dir, exist_ok=True)
		env = dict(os.environ, ODIN_ANDROID_NDK=ndk.root)
		code, out, err = run([odin, "build", odin_src, f"-target:linux_{abi}", "-subtarget:android", "-build-mode:llvm-ir", "-use-single-module", "-no-entry-point", f"-out:{ll_dir}"], env=env)
		if code != 0:
			print(out + err)
			raise GenError(f"odin probe failed for {abi}")
		odin_vals = {}
		for fn in os.listdir(ll_dir):
			if fn.endswith(".ll"):
				with open(os.path.join(ll_dir, fn), encoding="utf-8", errors="replace") as f:
					for line in f:
						m = re.match(r'^@"?(\w+)"?\s*=.*?global i64 (-?\d+)', line)
						if m:
							odin_vals[m.group(1)] = int(m.group(2))

		c_path = os.path.join(tmp, f"probe_{abi}.c")
		with open(c_path, "w", encoding="utf-8", newline="\n") as f:
			f.write(translation_unit(includes))
			f.write("#include <stddef.h>\n")
			for sym, _, expr in probes:
				f.write(f"const long long {sym} = (long long)({expr});\n")
		c_ll = os.path.join(tmp, f"probe_{abi}_c.ll")
		code, out, err = run([ndk.clang, f"--target={triple}{level}", "-S", "-emit-llvm", "-w", "-o", c_ll, c_path])
		if code != 0:
			print(err[:4000])
			raise GenError(f"clang probe failed for {abi}")
		c_vals = {}
		with open(c_ll, encoding="utf-8") as f:
			for line in f:
				m = re.match(r"^@(\w+)\s*=.*?constant i64 (-?\d+)", line)
				if m:
					c_vals[m.group(1)] = int(m.group(2))

		bad = [(s, odin_vals.get(s), c_vals.get(s)) for s, _, _ in probes if odin_vals.get(s) != c_vals.get(s)]
		print(f"{model.target.name} {abi}: {len(probes)} probes, {len(bad)} mismatches")
		for s, o, c in bad[:200]:
			print(f"\t{s}: odin={o} c={c}")
		ok = ok and not bad

		# Link every function and variable against the newest stubs.
		link_src = os.path.join(tmp, f"link_{abi}")
		os.makedirs(link_src, exist_ok=True)
		with open(os.path.join(link_src, "link.odin"), "w", encoding="utf-8", newline="\n") as f:
			f.write(f"package link\n\nimport {pkg} \"{imp}\"\n\n")
			f.write("@(export, link_name=\"odin_android_refs\")\nrefs := [?]rawptr{\n")
			for out_file in model.files:
				for item in model.files[out_file]:
					if item[0] == "func":
						f.write(f"\trawptr({pkg}.{item[1]['name']}),\n")
					elif item[0] == "var":
						f.write(f"\trawptr(&{pkg}.{item[1]['name']}),\n")
			f.write("}\n")
		so = os.path.join(tmp, f"link_{abi}.so")
		code, out, err = run([odin, "build", link_src, f"-target:linux_{abi}", "-subtarget:android", f"-minimum-os-version:{level}", "-build-mode:shared", f"-out:{so}"], env=env)
		if code != 0:
			print(out + err)
			ok = False
		print(f"{model.target.name} {abi}: link {'ok' if code == 0 else 'FAILED'}")
	return ok


#
# Main
#

def main():
	ap = argparse.ArgumentParser(description="Generate core:sys/android and vendor:android from the Android NDK headers.")
	ap.add_argument("--ndk", default=os.environ.get("ODIN_ANDROID_NDK"), help="NDK root (default: $ODIN_ANDROID_NDK)")
	ap.add_argument("--target", choices=[t.name for t in TARGETS], help="generate only this target (default: all)")
	ap.add_argument("--verify", action="store_true", help="compare layouts and constants with clang, and link every binding")
	ap.add_argument("--odin", default=os.path.join(ODIN_ROOT, "odin.exe" if os.name == "nt" else "odin"), help="Odin compiler for --verify")
	args = ap.parse_args()

	if not args.ndk:
		sys.exit("error: pass --ndk or set ODIN_ANDROID_NDK")

	ok = True
	try:
		ndk = NDK(args.ndk)
		triple = ABIS[0][1]
		core_includes = [h for h, _ in CORE.headers]

		by_name = {t.name: t for t in TARGETS}

		# The targets to generate, and every target whose types they use.
		needed = {CORE.name}
		pending = [t.name for t in TARGETS if args.target in (None, t.name)]
		while pending:
			name = pending.pop()
			if name not in needed:
				needed.add(name)
				pending += by_name[name].uses

		with tempfile.TemporaryDirectory(prefix="odin_android_gen_") as tmp:
			models = {}
			for target in TARGETS:
				if target.name not in needed:
					continue
				wanted = args.target in (None, target.name)

				# A target sees the headers of `core` and its `uses`, so their types resolve to those packages.
				bases    = [models[CORE.name]] + [models[u] for u in target.uses] if target is not CORE else []
				includes = list(dict.fromkeys(core_includes + [h for b in bases for h, _ in b.target.headers] + [h for h, _ in target.headers]))

				exports, first_level, other_exports, newest = read_exports(ndk, triple, target.libraries)
				ast    = dump_ast(ndk, triple, newest, includes, tmp)
				macros = dump_macros(ndk, triple, newest, tmp)
				model  = build_model(ndk, ast, macros, exports, first_level, other_exports, target, bases)
				models[target.name] = model
				if not wanted:
					continue

				values, strings = evaluate_constants(ndk, triple, newest, model, includes, tmp)
				for name, (out_file, _) in model.const_sources.items():
					model.constants[name] = out_file

				outputs = {}
				for out_file in dict.fromkeys(f for _, f in target.headers):
					text = emit_file(model, out_file, values, strings, ndk)
					if text is not None:
						outputs[out_file] = text

				# Only overwrite or delete generated files.
				os.makedirs(target.out_dir, exist_ok=True)
				for fn in os.listdir(target.out_dir):
					path = os.path.join(target.out_dir, fn)
					if fn.endswith(".odin") and fn[:-5] not in outputs:
						with open(path, encoding="utf-8") as f:
							if f.readline().rstrip("\r\n") == GENERATED_MARKER:
								os.remove(path)
				for out_file, text in outputs.items():
					path = os.path.join(target.out_dir, out_file + ".odin")
					if os.path.exists(path):
						with open(path, encoding="utf-8") as f:
							if f.readline().rstrip("\r\n") != GENERATED_MARKER:
								raise GenError(f"{path} is hand-written; refusing to overwrite it")
					with open(path, "w", encoding="utf-8", newline="\n") as f:
						f.write(text)

				print(f"{target.name}: wrote {len(outputs)} files to {target.out_dir}")
				for name, why in model.skipped:
					print(f"{target.name}: skipped {name}: {why}")

				if args.verify:
					ok = verify(ndk, model, values, includes, os.path.normpath(args.odin), tmp) and ok
	except GenError as e:
		sys.exit(f"error: {e}")
	if not ok:
		sys.exit(1)


if __name__ == "__main__":
	main()
