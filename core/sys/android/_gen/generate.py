def translation_unit(includes):
	return "".join(f"#include <{h}>\n" for h in includes)


def dump_ast(ndk, triple, level, includes, tmp):
	src = os.path.join(tmp, "tu.c")
	with open(src, "w", encoding="utf-8", newline="\n") as f:
		f.write(translation_unit(includes))
	code, out, err = run([ndk.clang, f"--target={triple}{level}", "-fsyntax-only", "-Xclang", "-ast-dump=json", src])
	if code != 0:
		raise GenError(f"clang failed:\n{err}")
	return json.loads(out)


def dump_macros(ndk, triple, level, tmp):
	src = os.path.join(tmp, "tu.c")
	code, out, err = run([ndk.clang, f"--target={triple}{level}", "-E", "-dD", src])
	if code != 0:
		raise GenError(f"clang -E failed:\n{err}")
	return out


class FileTracker:
	"""clang only prints a location's file and line when they change, in print order."""

	def __init__(self):
		self.file = None
		self.line = None

	def walk(self, obj, on_decl):
		if isinstance(obj, dict):
			if "file" in obj:
				self.file = obj["file"]
			if "line" in obj and ("offset" in obj):
				self.line = obj["line"]
			for key, value in list(obj.items()):
				if key == "includedFrom":
					continue
				self.walk(value, on_decl)
				if key == "loc" and "kind" in obj:
					obj["_file"] = self.file
					obj["_line"] = self.line
		elif isinstance(obj, list):
			for item in obj:
				self.walk(item, on_decl)


def header_of(ndk, path):
	if path is None:
		return None
	# Compared without case on Windows, but returned in its own case (`aaudio/AAudio.h`).
	full = os.path.normpath(path)
	inc  = os.path.normpath(ndk.include) + os.sep
	if not os.path.normcase(full).startswith(os.path.normcase(inc)):
		return None
	return full[len(inc):].replace(os.sep, "/")


