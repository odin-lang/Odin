def align_lines(rows, indent):
	"""rows: [(left, sep, right, trailing)] -> lines with `sep` aligned."""
	width = max((len(r[0]) for r in rows), default=0)
	lines = []
	for left, sep, right, trailing in rows:
		line = f"{indent}{left}{' ' * (width - len(left))}{sep}{right}"
		if trailing:
			line += trailing
		lines.append(line.rstrip())
	return lines


def emit_record(ctx, rec, indent):
	head = "struct"
	if rec.union:
		head += " #raw_union"
	if rec.packed:
		head += " #packed"
	if rec.opaque:
		return f"{head} {{}}"
	rows = []
	for i, (fname, ftype, nested, node) in enumerate(rec.fields):
		if nested is not None:
			body = emit_record(ctx, nested, indent + "\t")
			if strip_const(ftype)[0] == "array":
				raise GenError(f"array of anonymous record in {rec.name}")
			if fname is None:
				rows.append(("using _", ": ", body + ",", None))
			else:
				rows.append((odin_ident(fname), ": ", body + ",", None))
			continue
		names = source_param_names(ctx.model, node, rec.header, ftype)
		ftext = (slot_type(ctx, rec.name, fname) if rec.name and fname else None) or odin_type(ctx, ftype, "field", names)
		rows.append((odin_ident(fname or f"_{i}"), ": ", ftext + ",", None))
	lines = [f"{head} {{"]
	# Align the field types, but not across nested multi-line records.
	group = []
	for row in rows:
		if "\n" in row[2]:
			lines += align_lines(group, indent + "\t")
			group = []
			lines.append(f"{indent}\t{row[0]}: {row[2]}")
		else:
			group.append((row[0] + ":", " ", row[2], None))
	lines += align_lines(group, indent + "\t")
	lines.append(f"{indent}}}")
	return "\n".join(lines)


def dispatch_table(model, name, t):
	"""
	Whether typedef `name` points at a table of functions that take it back as their first
	parameter, so it can be modelled for Odin's `x->f(...)` (`x.f(x, ...)`):

	- "env": `typedef const struct JNINativeInterface* JNIEnv`, whose functions take `JNIEnv*`.
	  Emitted as `struct { using functions: ^JNINativeInterface }`, as C++'s `jni.h` does.
	- "itf": `typedef const struct SLObjectItf_* const* SLObjectItf`, whose functions take `SLObjectItf`.
	  Emitted as `^struct { using itf: ^SLObjectItf_ }`.

	Both have the C layout. Returns (shape, Odin record name) or None.
	"""
	t = strip_const(t)
	if t[0] != "ptr":
		return None
	inner = strip_const(t[1])
	if inner[0] == "ptr":
		shape, record_type, self_type = "itf", strip_const(inner[1]), ("named", name)
	else:
		shape, record_type, self_type = "env", inner, ("ptr", ("named", name))
	if record_type[0] != "tag":
		return None

	key  = f"{record_type[1]} {record_type[2]}"
	odin = model.tag_names.get(key)
	rec  = next((r for r in model.records.values() if r.name == odin), None)
	if rec is None or rec.opaque:
		return None

	functions = 0
	for _, ftype, _, _ in rec.fields:
		ftype = strip_const(ftype)
		if ftype[0] != "ptr" or strip_const(ftype[1])[0] != "func":
			continue
		params = strip_const(ftype[1])[2]
		if not params or strip_const(params[0]) != self_type and not (self_type[0] == "ptr" and strip_const(params[0])[0] == "ptr" and strip_const(strip_const(params[0])[1]) == self_type[1]):
			return None
		functions += 1
	return (shape, odin) if functions else None


def emit_file(model, out_file, values, strings, ndk):
	ctx = Ctx(model, out_file)
	items = model.files[out_file]

	blocks = []
	funcs  = defaultdict(list)  # library -> [row]
	vars_  = defaultdict(list)

	emitted_consts = set()

	def const_rows(names):
		rows = []
		for name in names:
			if name in emitted_consts or model.constants.get(name, out_file) != out_file:
				continue
			if name in strings:
				rows.append((name, " :: ", strings[name], None))
			elif name in values:
				rows.append((name, " :: ", format_constant(name, values[name], model), None))
			else:
				continue
			emitted_consts.add(name)
		return rows

	def one_liner(name, rhs):
		# Runs of one-line declarations share one aligned block.
		if blocks and isinstance(blocks[-1], list):
			blocks[-1].append((name, " :: ", rhs, None))
		else:
			blocks.append([(name, " :: ", rhs, None)])

	for index, item in enumerate(items):
		kind = item[0]
		if kind == "record":
			rec = item[1]
			body = emit_record(ctx, rec, "")
			if rec.note:
				blocks.append(f"// {rec.note}\n{rec.name} :: {body}")
			elif "\n" in body:
				blocks.append(f"{rec.name} :: {body}")
			else:
				one_liner(rec.name, body)

		elif kind == "typedef":
			_, name, t, node, header = item
			if name in model.pair_names:
				continue  # emitted as the enum before it
			names = source_param_names(model, node, header, t)
			table = dispatch_table(model, name, t)
			func = strip_const(t)
			if func[0] == "ptr":
				func = strip_const(func[1])
			if table:
				shape, record = table
				if shape == "env":
					blocks.append(f"{name} :: struct {{\n\tusing functions: ^{record},\n}}")
				else:
					one_liner(name, f"^struct {{ using itf: ^{record} }}")
			elif func[0] == "func":
				one_liner(name, odin_proc_type(ctx, func, names, owner=name))
			else:
				one_liner(name, odin_type(ctx, t, "typedef", names))

		elif kind == "enum":
			_, node, name, consts = item
			rows = const_rows([c for c in consts if c not in model.typed_consts])
			if rows:
				blocks.append("\n".join(align_lines(rows, "")))
			for te in model.anchored.get((out_file, index), []):
				blocks.append(emit_typed(ctx, te, values))
				emitted_consts.update(te.consts)

		elif kind == "func":
			_, node, lib, level = item
			ftype = parse_type(node["type"]["qualType"])
			if ftype[0] != "func":
				raise GenError(f"{node['name']} is not a function type")
			names = []
			for i, p in enumerate(n for n in node.get("inner", []) if n.get("kind") == "ParmVarDecl"):
				names.append(param_ident(p["name"]) if p.get("name") else f"_{i}")
			if len(names) != len(ftype[2]) or len(set(names)) != len(names):
				names = [f"_{i}" for i in range(len(ftype[2]))]
			no_return = any(a.get("kind") in ("NoReturnAttr", "C11NoReturnAttr", "CXX11NoReturnAttr") for a in node.get("inner", [])) or "noreturn" in node["type"]["qualType"]
			sig = odin_proc_type(ctx, ftype, names, no_return, owner=node["name"]).replace('proc "c" ', "proc", 1)
			trailing = f" // API level {level}" if level and level > MIN_API_LEVEL else None
			funcs[lib].append((node["name"], " :: ", sig + " ---", trailing))

		elif kind == "var":
			_, node, lib = item
			vars_[lib].append((node["name"] + ":", " ", odin_type(ctx, parse_type(node["type"]["qualType"]), "field"), None))

	# Macros that belong to no enum, in source order.
	macro_names = [n for n, (f, src) in model.const_sources.items() if f == out_file and src[0] == "macro" and n not in model.typed_consts]
	rows = const_rows(macro_names)
	if rows:
		blocks.append("\n".join(align_lines(rows, "")))
	for te in model.anchored.get((out_file, "macros"), []):
		blocks.append(emit_typed(ctx, te, values))
		emitted_consts.update(te.consts)

	libraries = model.target.libraries
	libs = sorted(set(funcs) | set(vars_), key=lambda l: list(libraries).index(l))
	for lib in libs:
		name, _ = libraries[lib]
		lines = ["@(default_calling_convention=\"c\")", f"foreign {name} {{"]
		if vars_[lib]:
			lines += align_lines(vars_[lib], "\t")
			if funcs[lib]:
				lines.append("")
		lines += align_lines(funcs[lib], "\t")
		lines.append("}")
		blocks.append("\n".join(lines))

	if not blocks:
		return None  # e.g. a header of only function-like macros

	headers = [h for h, f in model.target.headers if f == out_file]
	text = [GENERATED_MARKER]
	text.append(f"// Source: {', '.join(f'<{h}>' for h in headers)} (NDK {ndk.release}, {ndk.revision})")
	text.append("#+build linux")
	text.append(f"package {model.target.package}")
	text.append("")
	imports = sorted(model.imports[out_file])
	if imports:
		packages = {t.import_path: t.package for t in TARGETS}
		for imp in imports:
			# An import is named after its path's last element, not its package (`vendor:android/media` is `media`).
			pkg = packages.get(imp)
			if pkg and pkg != imp.rsplit("/", 1)[-1]:
				text.append(f"import {pkg} \"{imp}\"")
			else:
				text.append(f"import \"{imp}\"")
		text.append("")
	for lib in libs:
		name, path = libraries[lib]
		text.append(f"foreign import {name} \"{path}\"")
	if libs:
		text.append("")
	rendered = ["\n".join(align_lines(b, "")) if isinstance(b, list) else b for b in blocks]
	text.append("\n\n".join(b for b in rendered if b))
	return "\n".join(text).rstrip() + "\n"


def emit_typed(ctx, te, values):
	"""An enum, a bit_set with its element enum, or a bit_field with its field enums, then its constants."""
	model = ctx.model
	if te.backing.startswith("c."):
		model.imports[ctx.out_file].add("core:c")

	def enum_block(name, backing, rows):
		return [f"{name} :: enum {backing} {{", *align_lines([(m, " = ", f"{v},", None) for m, v in rows], "\t"), "}"]

	lines = []
	if te.kind == "enum":
		lines += enum_block(te.name, te.backing, [(te.members[c], format_constant(c, values[c], model)) for c in te.consts])
	elif te.kind == "bit_set":
		lines += enum_block(te.element, te.backing, list(te.bits.items()))
		lines.append(f"{te.name} :: distinct bit_set[{te.element}; {te.backing}]")
	else:
		for ename, members in te.enums.items():
			lines += enum_block(ename, unsigned(te.backing), [(m, hex(v) if v > 9 else str(v)) for m, v in members.items()])
			lines.append("")
		rows = []
		for fname, ftype, bits, _ in te.fields:
			if ftype == "_":
				ftype = "u8" if bits <= 8 else "u16" if bits <= 16 else "u32" if bits <= 32 else "u64"
			elif ftype not in ("bool", *INT_BITS):
				ftype = odin_type(ctx, ("named", ftype), "field")
			rows.append((f"{fname}:", ftype, bits))
		name_w = max(len(r[0]) for r in rows)
		type_w = max(len(r[1]) for r in rows)
		lines.append(f"{te.name} :: bit_field {te.backing} {{")
		lines += [f"\t{n:<{name_w}} {t:<{type_w}} | {b}," for n, t, b in rows]
		lines.append("}")

	consts = []
	for c in te.typed:
		literal = te.literals[c]
		if literal is None:
			mask = (1 << INT_BITS[te.backing]) - 1
			consts.append((c, " :: ", f"transmute({te.name}){te.backing}({hex(values[c] & mask)})", None))
		else:
			consts.append((c, " :: ", f"{te.name}{literal}", None))
	consts += [(c, " :: ", format_constant(c, values[c], model), None) for c in te.untyped]
	if consts:
		lines.append("")
		lines += align_lines(consts, "")
	return "\n".join(lines)


