def odin_ident(name):
	return name + "_" if name in ODIN_KEYWORDS else name


def param_ident(name):
	# Bionic spells parameters `__name` to stay out of the user's namespace.
	stripped = name.lstrip("_")
	return odin_ident(stripped if stripped and not stripped[0].isdigit() else name)


