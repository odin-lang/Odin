class Record:
	def __init__(self, node, name, header):
		self.node   = node
		self.name   = name
		self.header = header
		self.union  = node.get("tagUsed") == "union"
		self.fields = []  # (name or None, type tree, nested Record or None, FieldDecl node)
		self.opaque = not node.get("completeDefinition", False)
		self.packed = any(a.get("kind") == "PackedAttr" for a in node.get("inner", []))
		self.note   = None  # a comment emitted above the record


class Model:
	def __init__(self, ndk, target, bases):
		self.ndk          = ndk
		self.target       = target
		self.bases        = list(bases)         # models of `core` and the target's `uses`, whose types it refers to
		self.files        = defaultdict(list)  # output file -> [("type"|"const_group"|"func"|"var", ...)]
		self.records      = {}                  # record node id -> Record
		self.tag_names    = {}                  # "struct X" -> Odin name
		self.typedefs     = {}                  # typedef name -> type tree
		self.type_names   = set()
		self.constants    = {}                  # name -> output file
		self.const_order  = []
		self.enum_types   = {}                  # enum node id -> Odin underlying type
		self.imports      = defaultdict(set)    # output file -> Odin import paths
		self.uses_va_list = set()
		self.c_spelling   = {}                  # Odin type name -> how C spells it (for --verify)
		self.skipped      = []
		self._headers     = {}

	def header_bytes(self, header):
		if header not in self._headers:
			with open(os.path.join(self.ndk.include, *header.split("/")), "rb") as f:
				self._headers[header] = f.read()
		return self._headers[header]


def build_model(ndk, ast, macros_text, exports, first_level, other_exports, target, bases=()):
	header_file = {h: f for h, f in target.headers}
	model = Model(ndk, target, bases)

	tracker = FileTracker()
	tracker.walk(ast, None)

	decls = []
	for node in ast.get("inner", []):
		header = header_of(ndk, node.get("_file"))
		if header in header_file and not node.get("isImplicit"):
			decls.append((header, node))

	by_id = {node["id"]: node for _, node in decls}

	# Records only forward-declared in the bound headers but defined elsewhere (e.g. `struct
	# timespec`) are external types and must be in EXTERNAL_RECORDS.
	# The same goes for records `core:sys/android` already has (e.g. `struct AHardwareBuffer`).
	defined_elsewhere = {tag for b in bases for tag in b.tag_names}
	for node in ast.get("inner", []):
		if node.get("kind") == "RecordDecl" and node.get("completeDefinition") and node.get("name"):
			if header_of(ndk, node.get("_file")) not in header_file:
				defined_elsewhere.add(f"{node.get('tagUsed', 'struct')} {node['name']}")
	decls = [
		(h, n) for h, n in decls
		if not (n["kind"] == "RecordDecl" and not n.get("completeDefinition") and f"{n.get('tagUsed', 'struct')} {n.get('name')}" in defined_elsewhere)
	]

	# First pass: names of records and enums, including typedef'd anonymous ones.
	typedef_target = {}
	for header, node in decls:
		if node["kind"] == "TypedefDecl":
			ref = find_decl_ref(node)
			if ref is not None and ref in by_id:
				target = by_id[ref]
				if target["kind"] in ("RecordDecl", "EnumDecl"):
					# The first typedef names an anonymous record, a same-named one any record.
					tag = target.get("name")
					if target["id"] not in typedef_target or tag == node["name"]:
						typedef_target[target["id"]] = node["name"]

	for header, node in decls:
		if node["kind"] in ("RecordDecl", "EnumDecl"):
			name = typedef_target.get(node["id"]) or node.get("name")
			kw = "enum" if node["kind"] == "EnumDecl" else node.get("tagUsed", "struct")
			if node.get("name"):
				model.tag_names[f"{kw} {node['name']}"] = name
			elif name:
				# clang spells `typedef struct {...} X;` as `struct X` in places.
				model.tag_names.setdefault(f"{kw} {name}", name)

	# Constants: enum constants and object-like macros, valued by clang later. The source
	# text of an initializer only decides how the value is spelled.
	const_sources = {}
	for header, node in decls:
		if node["kind"] == "EnumDecl":
			for c in node.get("inner", []):
				if c.get("kind") == "EnumConstantDecl":
					const_sources[c["name"]] = (header_file[header], ("enum", enum_initializer_text(c, model.header_bytes(header))))

	for name, (header, text) in parse_macros(ndk, macros_text, header_file).items():
		if name not in const_sources:
			const_sources[name] = (header_file[header], ("macro", text))

	model.const_sources = const_sources

	# Second pass: emit in source order.
	seen_records = set()
	for header, node in decls:
		out  = header_file[header]
		kind = node["kind"]

		if kind == "RecordDecl":
			name = typedef_target.get(node["id"]) or node.get("name")
			if not name:
				continue
			if node["id"] in seen_records:
				continue
			# Forward declarations are skipped if the definition follows.
			if not node.get("completeDefinition") and any(
				n.get("kind") == "RecordDecl" and n.get("name") == node.get("name") and n.get("completeDefinition")
				for _, n in decls
			):
				continue
			seen_records.add(node["id"])
			if name in model.type_names:
				continue
			rec = build_record(model, node, name, header)
			model.type_names.add(name)
			model.c_spelling[name] = name if name in typedef_target.values() else f"{node.get('tagUsed', 'struct')} {name}"
			model.files[out].append(("record", rec))

		elif kind == "EnumDecl":
			name = typedef_target.get(node["id"]) or node.get("name")
			consts = [c["name"] for c in node.get("inner", []) if c.get("kind") == "EnumConstantDecl"]
			model.files[out].append(("enum", node, name, consts))
			if name:
				model.type_names.add(name)
				model.c_spelling[name] = name if name in typedef_target.values() else f"enum {name}"

		elif kind == "TypedefDecl":
			name = node["name"]
			ref  = find_decl_ref(node)
			if ref in by_id and typedef_target.get(ref) == name:
				continue  # emitted as the record or enum itself
			t = parse_type(node["type"]["qualType"])
			model.typedefs[name] = t
			if name in model.type_names:
				continue
			model.type_names.add(name)
			model.c_spelling[name] = name
			model.files[out].append(("typedef", name, t, node, header))

		elif kind == "FunctionDecl":
			name = node["name"]
			if node.get("storageClass") == "static" or node.get("inline"):
				model.skipped.append((name, "static inline"))
				continue
			lib = exports.get(name)
			if lib is None:
				if name in other_exports:
					raise GenError(f"{name} ({header}) is exported by {other_exports[name]}, which `core:sys/android` does not link")
				model.skipped.append((name, "not exported by any library"))
				continue
			model.files[out].append(("func", node, lib, first_level.get(name)))

		elif kind == "VarDecl":
			name = node["name"]
			lib = exports.get(name)
			if lib is None:
				model.skipped.append((name, "variable not exported by any library"))
				continue
			model.files[out].append(("var", node, lib))

	# C keeps struct tags apart from functions, Odin does not (`struct sync_file_info` and `sync_file_info()`).
	# The record gets `_t`, as in `core:sys/posix` (`stat_t`).
	procs = {item[1]["name"] for items in model.files.values() for item in items if item[0] in ("func", "var")}
	for items in model.files.values():
		for item in items:
			if item[0] == "record" and item[1].name in procs:
				rec = item[1]
				old, new = rec.name, rec.name + "_t"
				rec.name = new
				rec.note = f"NOTE(bill): `{old}` is also a procedure. The type has `_t` added."
				model.type_names.discard(old)
				model.type_names.add(new)
				model.c_spelling[new] = model.c_spelling.pop(old)
				for key, value in model.tag_names.items():
					if value == old:
						model.tag_names[key] = new

	return model


def enum_initializer_text(node, text):
	r = node.get("range", {})
	begin, end = r.get("begin", {}), r.get("end", {})
	if "offset" not in begin or "offset" not in end:
		return None  # spelled through a macro
	decl = text[begin["offset"]:end["offset"]+end.get("tokLen", 0)].decode("utf-8", "replace")
	if "=" not in decl:
		return None
	return decl.split("=", 1)[1].strip()


def find_decl_ref(node):
	"""The record or enum a typedef names directly (not through a pointer)."""
	def search(n):
		if not isinstance(n, dict):
			return None
		kind = n.get("kind", "")
		# `typedef A B;` names `A`, not the record behind it.
		if kind in ("PointerType", "FunctionProtoType", "ConstantArrayType", "IncompleteArrayType", "TypedefType"):
			return None
		if kind in ("RecordType", "EnumType") and "decl" in n:
			return n["decl"]["id"]
		for child in n.get("inner", []):
			r = search(child)
			if r is not None:
				return r
		return None
	for child in node.get("inner", []):
		r = search(child)
		if r is not None:
			return r
	return None


def build_record(model, node, name, header):
	rec = Record(node, name, header)
	pending_anon = None
	for child in node.get("inner", []):
		kind = child.get("kind")
		if kind == "RecordDecl":
			if child.get("name"):
				raise GenError(f"named nested record {child['name']} in {name}")
			pending_anon = build_record(model, child, None, header)
		elif kind == "FieldDecl":
			if child.get("isBitfield"):
				raise GenError(f"bit-field {child.get('name')} in {name} is not supported")
			qual = child["type"]["qualType"]
			fname = child.get("name") or None
			if "__ANON__" in ANON_RE.sub("__ANON__", qual):
				if pending_anon is None:
					raise GenError(f"anonymous type without a record in {name}.{fname}")
				rec.fields.append((fname, parse_type(qual), pending_anon, child))
			else:
				rec.fields.append((fname, parse_type(qual), None, child))
	model.records[node["id"]] = rec
	return rec


MACRO_LINE_RE = re.compile(r'^#\s+\d+\s+"([^"]+)"')
DEFINE_RE = re.compile(r"^#define\s+([A-Za-z_][A-Za-z0-9_]*)(\(?)\s*(.*)$")


def parse_macros(ndk, text, header_file):
	macros = {}
	current = None
	for line in text.splitlines():
		m = MACRO_LINE_RE.match(line)
		if m:
			current = header_of(ndk, m.group(1).replace("\\\\", "\\"))
			continue
		if current not in header_file:
			continue
		m = DEFINE_RE.match(line)
		if not m or m.group(2) == "(":
			continue
		name, value = m.group(1), m.group(3).strip()
		if name.startswith("_") or not value:
			continue
		macros[name] = (current, value)
	return macros


