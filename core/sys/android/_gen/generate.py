# Main
#

def main():
	ap = argparse.ArgumentParser(description="Generate core:sys/android and vendor:android from the Android NDK headers.")
	ap.add_argument("--ndk", default=os.environ.get("ODIN_ANDROID_NDK"), help="NDK root (default: $ODIN_ANDROID_NDK)")
	ap.add_argument("--target", choices=[t.name for t in TARGETS], help="generate only this target (default: all)")
	ap.add_argument("--verify", action="store_true", help="compare layouts and constants with clang, and link every binding")
	ap.add_argument("--odin", default=os.path.join(ODIN_ROOT, "odin.exe" if os.name == "nt" else "odin"), help="Odin compiler for --verify")
	args = ap.parse_args()

	if not args.ndk:
		sys.exit("error: pass --ndk or set ODIN_ANDROID_NDK")

	ok = True
	try:
		ndk = NDK(args.ndk)
		triple = ABIS[0][1]
		core_includes = [h for h, _ in CORE.headers]

		by_name = {t.name: t for t in TARGETS}

		# The targets to generate, and every target whose types they use.
		needed = {CORE.name}
		pending = [t.name for t in TARGETS if args.target in (None, t.name)]
		while pending:
			name = pending.pop()
			if name not in needed:
				needed.add(name)
				pending += by_name[name].uses

		with tempfile.TemporaryDirectory(prefix="odin_android_gen_") as tmp:
			models = {}
			for target in TARGETS:
				if target.name not in needed:
					continue
				wanted = args.target in (None, target.name)

				# A target sees the headers of `core` and its `uses`, so their types resolve to those packages.
				bases    = [models[CORE.name]] + [models[u] for u in target.uses] if target is not CORE else []
				includes = list(dict.fromkeys(core_includes + [h for b in bases for h, _ in b.target.headers] + [h for h, _ in target.headers]))

				exports, first_level, other_exports, newest = read_exports(ndk, triple, target.libraries)
				ast    = dump_ast(ndk, triple, newest, includes, tmp)
				macros = dump_macros(ndk, triple, newest, tmp)
				model  = build_model(ndk, ast, macros, exports, first_level, other_exports, target, bases)
				models[target.name] = model

				# Every model is planned, since the targets that use it refer to its types.
				values, strings = evaluate_constants(ndk, triple, newest, model, includes, tmp)
				plan_types(model, values)
				if not wanted:
					continue
				for name, (out_file, _) in model.const_sources.items():
					model.constants[name] = out_file

				outputs = {}
				for out_file in dict.fromkeys(f for _, f in target.headers):
					text = emit_file(model, out_file, values, strings, ndk)
					if text is not None:
						outputs[out_file] = text

				# Only overwrite or delete generated files.
				os.makedirs(target.out_dir, exist_ok=True)
				for fn in os.listdir(target.out_dir):
					path = os.path.join(target.out_dir, fn)
					if fn.endswith(".odin") and fn[:-5] not in outputs:
						with open(path, encoding="utf-8") as f:
							if f.readline().rstrip("\r\n") == GENERATED_MARKER:
								os.remove(path)
				for out_file, text in outputs.items():
					path = os.path.join(target.out_dir, out_file + ".odin")
					if os.path.exists(path):
						with open(path, encoding="utf-8") as f:
							if f.readline().rstrip("\r\n") != GENERATED_MARKER:
								raise GenError(f"{path} is hand-written; refusing to overwrite it")
					with open(path, "w", encoding="utf-8", newline="\n") as f:
						f.write(text)

				print(f"{target.name}: wrote {len(outputs)} files to {target.out_dir}")
				for name, why in model.skipped:
					print(f"{target.name}: skipped {name}: {why}")

				if args.verify:
					ok = verify(ndk, model, values, includes, os.path.normpath(args.odin), tmp) and ok
			if args.target is None:
				check_table(models.values())
	except GenError as e:
		sys.exit(f"error: {e}")
	if not ok:
		sys.exit(1)


if __name__ == "__main__":
	main()
