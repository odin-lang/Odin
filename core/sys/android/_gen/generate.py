class NDK:
	def __init__(self, root):
		self.root = os.path.normpath(root)
		prebuilt = os.path.join(self.root, "toolchains", "llvm", "prebuilt")
		hosts = os.listdir(prebuilt) if os.path.isdir(prebuilt) else []
		if not hosts:
			raise GenError(f"no prebuilt toolchain in {prebuilt}")
		self.toolchain = os.path.join(prebuilt, hosts[0])
		exe = ".exe" if os.name == "nt" else ""
		self.clang   = os.path.join(self.toolchain, "bin", "clang" + exe)
		self.nm      = os.path.join(self.toolchain, "bin", "llvm-nm" + exe)
		self.sysroot = os.path.join(self.toolchain, "sysroot")
		self.include = os.path.join(self.sysroot, "usr", "include")

		with open(os.path.join(self.root, "source.properties"), encoding="utf-8") as f:
			props = dict(line.split(" = ", 1) for line in f.read().splitlines() if " = " in line)
		self.release = props.get("Pkg.ReleaseName", "?")
		self.revision = props.get("Pkg.Revision", "?")

	def lib_dir(self, triple, level):
		lib_triple = "arm-linux-androideabi" if triple.startswith("armv7a") else triple
		return os.path.join(self.sysroot, "usr", "lib", lib_triple, str(level))

	def api_levels(self, triple):
		lib_triple = "arm-linux-androideabi" if triple.startswith("armv7a") else triple
		base = os.path.join(self.sysroot, "usr", "lib", lib_triple)
		return sorted(int(d) for d in os.listdir(base) if d.isdigit())


def run(cmd, **kwargs):
	p = subprocess.run(cmd, capture_output=True, text=True, errors="replace", **kwargs)
	return p.returncode, p.stdout, p.stderr


#
# Stub libraries: which library exports a symbol, and since which API level
#

def read_exports(ndk, triple, libraries):
	levels  = ndk.api_levels(triple)
	newest  = levels[-1]
	library = {}
	first   = {}
	for level in levels:
		for lib in libraries:
			path = os.path.join(ndk.lib_dir(triple, level), lib)
			if not os.path.exists(path):
				continue
			code, out, err = run([ndk.nm, "-D", "--defined-only", path])
			if code != 0:
				raise GenError(err)
			for line in out.splitlines():
				parts = line.split()
				if len(parts) < 3:
					continue
				sym = parts[2].split("@")[0]
				first.setdefault(sym, level)
				if level == newest:
					library[sym] = lib

	# Libraries outside the target's, so a misplaced header can be reported.
	other = {}
	for lib in os.listdir(ndk.lib_dir(triple, newest)):
		if lib.endswith(".so") and lib not in libraries:
			code, out, _ = run([ndk.nm, "-D", "--defined-only", os.path.join(ndk.lib_dir(triple, newest), lib)])
			for line in out.splitlines():
				parts = line.split()
				if len(parts) >= 3:
					other.setdefault(parts[2].split("@")[0], lib)
	return library, first, other, newest


