class Ctx:
	def __init__(self, model, out_file):
		self.model    = model
		self.out_file = out_file


def resolve_typedef(model, t):
	seen = set()
	while t[0] == "named" and t[1] not in seen:
		seen.add(t[1])
		owner = next((m for m in [model, *model.bases] if t[1] in m.typedefs), None)
		if owner is None:
			break
		t = owner.typedefs[t[1]]
	return t


def odin_type(ctx, t, where, names=None):
	model = ctx.model
	kind = t[0]
	if kind == "const":
		return odin_type(ctx, t[1], where, names)
	if kind == "builtin":
		if t[1] not in BUILTIN_TYPES:
			raise GenError(f"unknown builtin type {t[1]!r}")
		mapped = BUILTIN_TYPES[t[1]]
		if mapped is None:
			raise GenError("`void` used as a value type")
		if mapped.startswith("c."):
			model.imports[ctx.out_file].add("core:c")
		return mapped
	if kind == "named":
		name = t[1]
		if name in model.type_names:
			return name
		for base in model.bases:
			if name in base.type_names:
				model.imports[ctx.out_file].add(base.target.import_path)
				return f"{base.target.package}.{name}"
		if name in EXTERNAL_TYPES:
			mapped = EXTERNAL_TYPES[name]
			if mapped.startswith("c."):
				model.imports[ctx.out_file].add("core:c")
			if mapped == "va_list_arg":
				model.uses_va_list.add(ctx.out_file)
				if model.target is not CORE:
					model.imports[ctx.out_file].add(CORE.import_path)
					return f"{CORE.package}.va_list_arg"
			return mapped
		raise GenError(f"unknown type {name!r}")
	if kind == "tag":
		key = f"{t[1]} {t[2]}"
		if key in model.tag_names:
			return model.tag_names[key]
		for base in model.bases:
			if key in base.tag_names:
				model.imports[ctx.out_file].add(base.target.import_path)
				return f"{base.target.package}.{base.tag_names[key]}"
		if key in EXTERNAL_RECORDS:
			imp, mapped = EXTERNAL_RECORDS[key]
			model.imports[ctx.out_file].add(imp)
			return mapped
		raise GenError(f"unknown record {key!r}")
	if kind == "ptr":
		pointee = t[1]
		bare    = strip_const(pointee)
		target  = resolve_typedef(model, bare)
		if target[0] == "func":
			return odin_type(ctx, bare, where, names)
		if bare == ("builtin", "void"):
			return "rawptr"
		if bare == ("builtin", "char"):
			if pointee[0] == "const" or where == "return":
				return "cstring"
			model.imports[ctx.out_file].add("core:c")
			return "[^]c.char"
		return "^" + odin_type(ctx, pointee, "pointee")
	if kind == "array":
		elem = odin_type(ctx, t[1], "field")
		return f"[{t[2] if t[2] is not None else 0}]{elem}"
	if kind == "func":
		return odin_proc_type(ctx, t, names)
	raise GenError(f"unhandled type {t!r}")


def split_top(s):
	"""Split on commas outside parentheses and brackets."""
	out, depth, cur = [], 0, ""
	for ch in s:
		if ch in "([":
			depth += 1
		elif ch in ")]":
			depth -= 1
		if ch == "," and depth == 0:
			out.append(cur.strip())
			cur = ""
		else:
			cur += ch
	if cur.strip() or out:
		out.append(cur.strip())
	return out


SOURCE_ATTR_RE = re.compile(r"\b__\w+\s*\((?:[^()]|\([^()]*\))*\)")
SOURCE_COMMENT_RE = re.compile(r"/\*.*?\*/|//[^\n]*", re.S)


def decl_source(model, node, header):
	r = node.get("range", {})
	begin, end = r.get("begin", {}), r.get("end", {})
	if "offset" not in begin or "offset" not in end:
		return None
	text = model.header_bytes(header)
	return text[begin["offset"]:end["offset"]+end.get("tokLen", 0)].decode("utf-8", "replace")


def source_param_names(model, node, header, t):
	"""Parameter names of a function-pointer typedef or field, read from the header.

	clang's type strings drop them. Returns None unless every parameter has an unambiguous name.
	"""
	t = strip_const(t)
	if t[0] == "ptr":
		t = strip_const(t[1])
	if t[0] != "func":
		return None
	text = decl_source(model, node, header)
	if text is None:
		return None
	text = SOURCE_COMMENT_RE.sub(" ", text)
	text = SOURCE_ATTR_RE.sub(" ", text).rstrip().rstrip(";").rstrip()
	if not text.endswith(")"):
		return None

	depth, start = 0, None
	for i in range(len(text)-1, -1, -1):
		if text[i] == ")":
			depth += 1
		elif text[i] == "(":
			depth -= 1
			if depth == 0:
				start = i
				break
	if start is None:
		return None
	params = split_top(text[start+1:-1])
	if params in ([], ["void"], [""]):
		params = []
	if params and params[-1] == "...":
		params = params[:-1]
	if len(params) != len(t[2]):
		return None

	names = []
	for p in params:
		if "(" in p or "[" in p:
			return None
		toks = [tok for tok in re.findall(r"[A-Za-z_]\w*", p) if tok not in DROPPED_QUALIFIERS and tok != "const"]
		if len(toks) < 2:
			return None
		last = toks[-1]
		if last in BUILTIN_WORDS or last in model.type_names or last in EXTERNAL_TYPES or toks[-2] in ("struct", "union", "enum"):
			return None
		names.append(param_ident(last))
	if len(set(names)) != len(names):
		return None
	return names


def odin_proc_type(ctx, t, param_names, no_return=False):
	_, ret, params, variadic = t
	parts = []
	for i, p in enumerate(params):
		pt = odin_type(ctx, p, "param")
		if param_names:
			parts.append(f"{param_names[i]}: {pt}")
		else:
			parts.append(pt)
	if variadic:
		parts.append("#c_vararg args: ..any" if param_names else "#c_vararg ..any")
	sig = f"proc \"c\" ({', '.join(parts)})"
	if no_return:
		return sig + " -> !"
	if strip_const(ret) != ("builtin", "void"):
		sig += " -> " + odin_type(ctx, ret, "return")
	return sig


