TOKEN_RE = re.compile(r"\s*(\.\.\.|[A-Za-z_][A-Za-z0-9_]*|\d+|[*()\[\],])")
DROPPED_QUALIFIERS = {"volatile", "restrict", "__restrict", "_Nonnull", "_Nullable", "_Null_unspecified", "_Nullable_result", "__unaligned"}
BUILTIN_WORDS = {"void", "char", "short", "int", "long", "signed", "unsigned", "float", "double", "_Bool", "bool", "__int128"}
ANON_RE = re.compile(r"(?:(?:struct|union|enum)\s+)?(?:[A-Za-z_]\w*::)*\((?:unnamed|anonymous)[^)]*\)")
ATTR_RE = re.compile(r"__attribute__\(\((?:[^()]|\([^()]*\))*\)\)")
# clang prints an attribute written through a macro by the macro's name: `__INTRODUCED_IN(36) const char *`.
MACRO_ATTR_RE = re.compile(r"\b__[A-Z][A-Z0-9_]*\s*\([^()]*\)")


def tokenize(s):
	s = ATTR_RE.sub("", s)
	s = MACRO_ATTR_RE.sub("", s)
	s = ANON_RE.sub("struct __ANON__", s)
	tokens, i = [], 0
	while i < len(s):
		m = TOKEN_RE.match(s, i)
		if not m:
			if s[i:].strip() == "":
				break
			raise GenError(f"cannot tokenize type {s!r} at {s[i:]!r}")
		tokens.append(m.group(1))
		i = m.end()
	return tokens


class TypeParser:
	def __init__(self, text):
		self.text = text
		self.toks = tokenize(text)
		self.pos  = 0

	def peek(self, k=0):
		i = self.pos + k
		return self.toks[i] if i < len(self.toks) else None

	def next(self):
		t = self.peek()
		self.pos += 1
		return t

	def expect(self, t):
		if self.next() != t:
			raise GenError(f"expected {t!r} in type {self.text!r}")

	def parse(self):
		t = self.parse_type()
		if self.peek() is not None:
			raise GenError(f"trailing tokens in type {self.text!r}")
		return t

	def parse_type(self):
		base = self.parse_specifiers()
		apply = self.parse_declarator()
		return apply(base)

	def parse_specifiers(self):
		is_const = False
		words    = []
		base     = None
		while True:
			t = self.peek()
			if t == "const":
				is_const = True
				self.next()
			elif t in DROPPED_QUALIFIERS:
				self.next()
			elif t in BUILTIN_WORDS and base is None:
				words.append(self.next())
			elif t in ("struct", "union", "enum") and base is None and not words:
				self.next()
				base = ("tag", t, self.next())
			elif t is not None and re.match(r"[A-Za-z_]", t) and base is None and not words:
				base = ("named", self.next())
			else:
				break
		if words:
			is_unsigned = "unsigned" in words
			is_signed   = "signed" in words
			rest = [w for w in words if w not in ("unsigned", "signed")]
			if rest == ["char"]:
				name = "unsigned char" if is_unsigned else "signed char" if is_signed else "char"
			else:
				rest = [w for w in rest if w != "int"] or ["int"]
				name = " ".join(rest)
				if is_unsigned:
					name = "unsigned " + name
			base = ("builtin", name)
		if base is None:
			raise GenError(f"no base type in {self.text!r}")
		return ("const", base) if is_const else base

	def parse_declarator(self):
		if self.peek() == "*":
			self.next()
			is_const = False
			while self.peek() in DROPPED_QUALIFIERS or self.peek() == "const":
				if self.next() == "const":
					is_const = True
			inner = self.parse_declarator()

			def apply(t, inner=inner, is_const=is_const):
				return inner(("ptr", t))
			return apply
		return self.parse_direct()

	def parse_direct(self):
		inner = None
		if self.peek() == "(" and self.peek(1) in ("*", "("):
			self.next()
			inner = self.parse_declarator()
			self.expect(")")
		suffixes = []
		while self.peek() in ("[", "("):
			if self.next() == "[":
				n = None
				if self.peek() != "]":
					n = int(self.next())
				self.expect("]")
				suffixes.append(("array", n))
			else:
				params, variadic = [], False
				if self.peek() == "void" and self.peek(1) == ")":
					self.next()
				while self.peek() != ")":
					if self.peek() == "...":
						self.next()
						variadic = True
					else:
						params.append(self.parse_type())
					if self.peek() == ",":
						self.next()
				self.expect(")")
				suffixes.append(("func", params, variadic))

		def apply(t, inner=inner, suffixes=suffixes):
			for s in reversed(suffixes):
				if s[0] == "array":
					t = ("array", t, s[1])
				else:
					t = ("func", t, s[1], s[2])
			return inner(t) if inner else t
		return apply


def parse_type(text):
	return TypeParser(text).parse()


def strip_const(t):
	while t[0] == "const":
		t = t[1]
	return t


