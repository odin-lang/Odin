def vendor_target(name, headers, libraries, uses=()):
	"""A `vendor:android/<name>` package called `android_<name>`. `libraries` are stub names without `lib` and `.so`."""
	libs = {f"lib{l}.so": (f"lib{l}", f"system:{l}") for l in libraries}
