class Record:
	def __init__(self, node, name, header):
		self.node   = node
		self.name   = name
		self.header = header
		self.union  = node.get("tagUsed") == "union"
		self.fields = []  # (name or None, type tree, nested Record or None, FieldDecl node)
		self.opaque = not node.get("completeDefinition", False)
		self.packed = any(a.get("kind") == "PackedAttr" for a in node.get("inner", []))
		self.note   = None  # a comment emitted above the record


class Model:
	def __init__(self, ndk, target, bases):
		self.ndk          = ndk
		self.target       = target
		self.bases        = list(bases)         # models of `core` and the target's `uses`, whose types it refers to
		self.files        = defaultdict(list)  # output file -> [("type"|"const_group"|"func"|"var", ...)]
		self.records      = {}                  # record node id -> Record
		self.tag_names    = {}                  # "struct X" -> Odin name
		self.typedefs     = {}                  # typedef name -> type tree
		self.type_names   = set()
		self.constants    = {}                  # name -> output file
		self.const_order  = []
		self.enum_types   = {}                  # enum node id -> Odin underlying type
		self.imports      = defaultdict(set)    # output file -> Odin import paths
		self.uses_va_list = set()
		self.c_spelling   = {}                  # Odin type name -> how C spells it (for --verify)
		self.skipped      = []
		self._headers     = {}
		self.typed        = {}                  # Odin type name -> TypedEnum (see plan_types)
		self.typed_consts = {}                  # C constant -> the TypedEnum that takes it
		self.anchored     = defaultdict(list)   # (output file, item index or "macros") -> TypedEnums emitted there
		self.pair_names   = set()               # integer typedefs emitted as the anonymous enum before them
		self.slot_types   = defaultdict(dict)   # function, callback or record -> {param index, "return" or field: type}

	def header_bytes(self, header):
		if header not in self._headers:
			with open(os.path.join(self.ndk.include, *header.split("/")), "rb") as f:
				self._headers[header] = f.read()
		return self._headers[header]


def build_model(ndk, ast, macros_text, exports, first_level, other_exports, target, bases=()):
	header_file = {h: f for h, f in target.headers}
	model = Model(ndk, target, bases)

	tracker = FileTracker()
	tracker.walk(ast, None)

	decls = []
	for node in ast.get("inner", []):
		header = header_of(ndk, node.get("_file"))
		if header in header_file and not node.get("isImplicit"):
			decls.append((header, node))

	by_id = {node["id"]: node for _, node in decls}

	# Records only forward-declared in the bound headers but defined elsewhere (e.g. `struct
	# timespec`) are external types and must be in EXTERNAL_RECORDS.
	# The same goes for records `core:sys/android` already has (e.g. `struct AHardwareBuffer`).
	defined_elsewhere = {tag for b in bases for tag in b.tag_names}
	for node in ast.get("inner", []):
		if node.get("kind") == "RecordDecl" and node.get("completeDefinition") and node.get("name"):
			if header_of(ndk, node.get("_file")) not in header_file:
				defined_elsewhere.add(f"{node.get('tagUsed', 'struct')} {node['name']}")
	decls = [
		(h, n) for h, n in decls
		if not (n["kind"] == "RecordDecl" and not n.get("completeDefinition") and f"{n.get('tagUsed', 'struct')} {n.get('name')}" in defined_elsewhere)
	]

	# First pass: names of records and enums, including typedef'd anonymous ones.
	typedef_target = {}
	for header, node in decls:
		if node["kind"] == "TypedefDecl":
			ref = find_decl_ref(node)
			if ref is not None and ref in by_id:
				target = by_id[ref]
				if target["kind"] in ("RecordDecl", "EnumDecl"):
					# The first typedef names an anonymous record, a same-named one any record.
					tag = target.get("name")
					if target["id"] not in typedef_target or tag == node["name"]:
						typedef_target[target["id"]] = node["name"]

	for header, node in decls:
		if node["kind"] in ("RecordDecl", "EnumDecl"):
			name = typedef_target.get(node["id"]) or node.get("name")
			kw = "enum" if node["kind"] == "EnumDecl" else node.get("tagUsed", "struct")
			if node.get("name"):
				model.tag_names[f"{kw} {node['name']}"] = name
			elif name:
				# clang spells `typedef struct {...} X;` as `struct X` in places.
				model.tag_names.setdefault(f"{kw} {name}", name)

	# Constants: enum constants and object-like macros, valued by clang later. The source
	# text of an initializer only decides how the value is spelled.
	const_sources = {}
	for header, node in decls:
		if node["kind"] == "EnumDecl":
			for c in node.get("inner", []):
				if c.get("kind") == "EnumConstantDecl":
					const_sources[c["name"]] = (header_file[header], ("enum", enum_initializer_text(c, model.header_bytes(header))))

	for name, (header, text) in parse_macros(ndk, macros_text, header_file).items():
		if name not in const_sources:
			const_sources[name] = (header_file[header], ("macro", text))

	model.const_sources = const_sources

	# Second pass: emit in source order.
	seen_records = set()
	for header, node in decls:
		out  = header_file[header]
		kind = node["kind"]

		if kind == "RecordDecl":
			name = typedef_target.get(node["id"]) or node.get("name")
			if not name:
				continue
			if node["id"] in seen_records:
				continue
			# Forward declarations are skipped if the definition follows.
			if not node.get("completeDefinition") and any(
				n.get("kind") == "RecordDecl" and n.get("name") == node.get("name") and n.get("completeDefinition")
				for _, n in decls
			):
				continue
			seen_records.add(node["id"])
			if name in model.type_names:
				continue
			rec = build_record(model, node, name, header)
			model.type_names.add(name)
			model.c_spelling[name] = name if name in typedef_target.values() else f"{node.get('tagUsed', 'struct')} {name}"
			model.files[out].append(("record", rec))

		elif kind == "EnumDecl":
			name = typedef_target.get(node["id"]) or node.get("name")
			consts = [c["name"] for c in node.get("inner", []) if c.get("kind") == "EnumConstantDecl"]
			model.files[out].append(("enum", node, name, consts))
			if name:
				model.type_names.add(name)
				model.c_spelling[name] = name if name in typedef_target.values() else f"enum {name}"

		elif kind == "TypedefDecl":
			name = node["name"]
			ref  = find_decl_ref(node)
			if ref in by_id and typedef_target.get(ref) == name:
				continue  # emitted as the record or enum itself
			t = parse_type(node["type"]["qualType"])
			model.typedefs[name] = t
			if name in model.type_names:
				continue
			model.type_names.add(name)
			model.c_spelling[name] = name
			model.files[out].append(("typedef", name, t, node, header))

		elif kind == "FunctionDecl":
			name = node["name"]
			if node.get("storageClass") == "static" or node.get("inline"):
				model.skipped.append((name, "static inline"))
				continue
			lib = exports.get(name)
			if lib is None:
				if name in other_exports:
					raise GenError(f"{name} ({header}) is exported by {other_exports[name]}, which `core:sys/android` does not link")
				model.skipped.append((name, "not exported by any library"))
				continue
			model.files[out].append(("func", node, lib, first_level.get(name)))

		elif kind == "VarDecl":
			name = node["name"]
			lib = exports.get(name)
			if lib is None:
				model.skipped.append((name, "variable not exported by any library"))
				continue
			model.files[out].append(("var", node, lib))

	# C keeps struct tags apart from functions, Odin does not (`struct sync_file_info` and `sync_file_info()`).
	# The record gets `_t`, as in `core:sys/posix` (`stat_t`).
	procs = {item[1]["name"] for items in model.files.values() for item in items if item[0] in ("func", "var")}
	for items in model.files.values():
		for item in items:
			if item[0] == "record" and item[1].name in procs:
				rec = item[1]
				old, new = rec.name, rec.name + "_t"
				rec.name = new
				rec.note = f"NOTE(bill): `{old}` is also a procedure. The type has `_t` added."
				model.type_names.discard(old)
				model.type_names.add(new)
				model.c_spelling[new] = model.c_spelling.pop(old)
				for key, value in model.tag_names.items():
					if value == old:
						model.tag_names[key] = new

	return model


def enum_initializer_text(node, text):
	r = node.get("range", {})
	begin, end = r.get("begin", {}), r.get("end", {})
	if "offset" not in begin or "offset" not in end:
		return None  # spelled through a macro
	decl = text[begin["offset"]:end["offset"]+end.get("tokLen", 0)].decode("utf-8", "replace")
	if "=" not in decl:
		return None
	return decl.split("=", 1)[1].strip()


def find_decl_ref(node):
	"""The record or enum a typedef names directly (not through a pointer)."""
	def search(n):
		if not isinstance(n, dict):
			return None
		kind = n.get("kind", "")
		# `typedef A B;` names `A`, not the record behind it.
		if kind in ("PointerType", "FunctionProtoType", "ConstantArrayType", "IncompleteArrayType", "TypedefType"):
			return None
		if kind in ("RecordType", "EnumType") and "decl" in n:
			return n["decl"]["id"]
		for child in n.get("inner", []):
			r = search(child)
			if r is not None:
				return r
		return None
	for child in node.get("inner", []):
		r = search(child)
		if r is not None:
			return r
	return None


def build_record(model, node, name, header):
	rec = Record(node, name, header)
	pending_anon = None
	for child in node.get("inner", []):
		kind = child.get("kind")
		if kind == "RecordDecl":
			if child.get("name"):
				raise GenError(f"named nested record {child['name']} in {name}")
			pending_anon = build_record(model, child, None, header)
		elif kind == "FieldDecl":
			if child.get("isBitfield"):
				raise GenError(f"bit-field {child.get('name')} in {name} is not supported")
			qual = child["type"]["qualType"]
			fname = child.get("name") or None
			if "__ANON__" in ANON_RE.sub("__ANON__", qual):
				if pending_anon is None:
					raise GenError(f"anonymous type without a record in {name}.{fname}")
				rec.fields.append((fname, parse_type(qual), pending_anon, child))
			else:
				rec.fields.append((fname, parse_type(qual), None, child))
	model.records[node["id"]] = rec
	return rec


MACRO_LINE_RE = re.compile(r'^#\s+\d+\s+"([^"]+)"')
DEFINE_RE = re.compile(r"^#define\s+([A-Za-z_][A-Za-z0-9_]*)(\(?)\s*(.*)$")


def parse_macros(ndk, text, header_file):
	macros = {}
	current = None
	for line in text.splitlines():
		m = MACRO_LINE_RE.match(line)
		if m:
			current = header_of(ndk, m.group(1).replace("\\\\", "\\"))
			continue
		if current not in header_file:
			continue
		m = DEFINE_RE.match(line)
		if not m or m.group(2) == "(":
			continue
		name, value = m.group(1), m.group(3).strip()
		if name.startswith("_") or not value:
			continue
		macros[name] = (current, value)
	return macros


#
# Constant values, from clang
#

INT_LITERAL_RE = re.compile(r"^\(?\s*(-?\s*(?:0[xX][0-9a-fA-F]+|\d+))[uUlL]*\s*\)?$")
STRING_RE = re.compile(r'^"(?:[^"\\]|\\.)*"$')
FLOAT_RE = re.compile(r"\d\.\d*|\d[eE][-+]?\d|\.\d")
FLOAT_LITERAL_RE = re.compile(r"^\(?\s*(?:\((?:double|float)\)\s*)?(-?\d+\.\d*(?:[eE][-+]?\d+)?)[fFlL]?\s*\)?$")


def evaluate_constants(ndk, triple, level, model, includes, tmp):
	names = sorted(model.const_sources)
	strings = {}
	numeric = []
	for name in names:
		src = model.const_sources[name][1]
		if src[0] == "macro" and STRING_RE.match(src[1]):
			strings[name] = src[1]
		elif src[0] == "macro" and FLOAT_RE.search(src[1]):
			m = FLOAT_LITERAL_RE.match(src[1])
			if m:
				literal = m.group(1)
				strings[name] = literal + "0" if literal.endswith(".") else literal
			else:
				model.skipped.append((name, f"floating-point macro {src[1]!r}"))
		else:
			numeric.append(name)

	values = {}
	remaining = list(numeric)
	for _ in range(20):
		path = os.path.join(tmp, "consts.c")
		with open(path, "w", encoding="utf-8", newline="\n") as f:
			f.write(translation_unit(includes))
			first = len(includes) + 1
			for i, name in enumerate(remaining):
				f.write(f"const long long __odin_const_{i} = (long long)({name}); const long long __odin_neg_{i} = (({name}) < 0);\n")
		ll = os.path.join(tmp, "consts.ll")
		code, out, err = run([ndk.clang, f"--target={triple}{level}", "-S", "-emit-llvm", "-w", "-ferror-limit=0", "-o", ll, path])
		if code == 0:
			break
		bad = set()
		for m in re.finditer(r"consts\.c:(\d+):\d+: error", err):
			bad.add(int(m.group(1)) - first)
		if not bad:
			raise GenError(err)
		remaining = [n for i, n in enumerate(remaining) if i not in bad]
	else:
		raise GenError("constant evaluation did not settle")

	negative = {}
	with open(ll, encoding="utf-8") as f:
		for line in f:
			m = re.match(r"^@__odin_(const|neg)_(\d+)\s*=.*?constant i64 (-?\d+)", line)
			if m and m.group(1) == "const":
				values[remaining[int(m.group(2))]] = int(m.group(3))
			elif m:
				negative[remaining[int(m.group(2))]] = m.group(3) != "0"
	# Unsigned 64-bit values (e.g. `1ULL << 63`) wrap through `long long`.
	for name, value in values.items():
		if value < 0 and not negative.get(name, True):
			values[name] = value + 2**64
	return values, strings


def format_constant(name, value, model):
	text = model.const_sources[name][1][1]
	if text is not None:
		m = INT_LITERAL_RE.match(text)
		if m and int(m.group(1).replace(" ", ""), 0) == value:
			return m.group(1).replace(" ", "")
		if re.search(r"0[xX]|<<|\|", text):
			return hex(value) if value >= 0 else str(value)
	return str(value)


#
# Typed constants: C enums, and the constants table.py groups, become Odin enums, bit_sets and bit_fields
#

# Odin integer types -> bits. ABI_SIZED_INTS differ between the 32-bit and 64-bit ABIs.
INT_BITS = {
	"i8":  8,  "u8":  8,  "c.schar": 8,  "c.uchar": 8, "c.char": 8,
	"i16": 16, "u16": 16, "c.short": 16, "c.ushort": 16,
	"i32": 32, "u32": 32, "c.int": 32,   "c.uint": 32, "rune": 32,
	"i64": 64, "u64": 64, "c.longlong": 64, "c.ulonglong": 64,
}
ABI_SIZED_INTS = {"c.long", "c.ulong", "int", "uintptr", "c.size_t", "c.ssize_t"}

# ("slot" or "pointer", rule index) -> slots the rule typed, over every planned model.
RULE_HITS = Counter()


class TypedEnum:
	"""An Odin enum, bit_set or bit_field made from C constants."""

	def __init__(self, name, kind, consts):
		self.name     = name
		self.kind     = kind    # "enum", "bit_set" or "bit_field"
		self.consts   = consts  # the C constants it takes, in source order
		self.backing  = None    # Odin integer type
		self.element  = None    # bit_set: its element enum
		self.members  = {}      # C constant -> enum member, or bit_set element
		self.bits     = {}      # bit_set: element -> bit
		self.typed    = []      # C constants that become typed constants of the type, under their C names
		self.literals = {}      # typed constant -> its Odin literal
		self.untyped  = []      # constants of a named C enum that stay untyped (a bit_field's masks)
		self.dropped  = []      # C constants that go entirely
		self.enums    = {}      # bit_field: the field enums it declares -> {member: value}
		self.fields   = []      # bit_field: (name, type, bits, offset)


def table_members(spec, names):
	"""The names a table.py members spec picks, in the order of `names`."""
	if isinstance(spec, str):
		return [n for n in names if n.startswith(spec)]
	picked = []
	for n in names:
		hit = False
		for pattern in spec:
			negated = pattern.startswith("!")
			if fnmatch.fnmatchcase(n, pattern[1:] if negated else pattern):
				hit = not negated
		if hit:
			picked.append(n)
	return picked


def shared_prefix(names):
	"""The prefix all names share, up to its last `_`."""
	if len(names) < 2:
		return ""
	p = os.path.commonprefix(names)
	return p[:p.rfind("_") + 1]


def member_name(type_name, short):
	"""`short` as an Odin identifier: `_12KEY`, or `NUM0` for a number key."""
	if short[:1].isdigit():
		return ("NUM" if type_name in TABLE.NUMBER_KEYS and short.isdigit() else "_") + short
	return short


def element_name(name):
	"""The element enum of a bit_set, as in darwin: the singular, or `Flag` added."""
	if name.endswith("Flags"):
		return name[:-1]
	if name.endswith(("uses", "sses", "xes")):
		return name[:-2]
	if name.endswith("ies"):
		return name[:-3] + "y"
	if name.endswith("s") and not name.endswith("ss"):
		return name[:-1]
	return name + "Flag"


def int_type(model, t):
	"""The Odin integer type a C type tree resolves to, or None for anything else."""
	t = strip_const(resolve_typedef(model, strip_const(t)))
	if t[0] == "builtin":
		mapped = BUILTIN_TYPES.get(t[1])
	elif t[0] == "named":
		mapped = EXTERNAL_TYPES.get(t[1])
	else:
		return None
	return mapped if mapped in INT_BITS or mapped in ABI_SIZED_INTS else None


def find_typed(model, name):
	for m in [model, *model.bases]:
		if name in m.typed:
			return m.typed[name]
	return None


def c_typed(model, t):
	"""The TypedEnum a C type already names (a C enum, or a typedef'd anonymous one), or None."""
	t = strip_const(t)
	if t[0] == "named":
		return find_typed(model, t[1])
	if t[0] == "tag" and t[1] == "enum":
		key = f"enum {t[2]}"
		for m in [model, *model.bases]:
			if key in m.tag_names:
				return find_typed(model, m.tag_names[key])
	return None


def unsigned(backing):
	bits = INT_BITS.get(backing)
	if bits is None:
		raise GenError(f"no fixed size for {backing}")
	return f"u{bits}"


def plan_types(model, values):
	"""Decide a model's enums, bit_sets and bit_fields, and the slots table.py gives them. Needs its bases planned."""
	names = [n for n in model.const_sources if n in values]  # integer constants, in source order
	item_of = {}  # constant -> (output file, index) of the C enum declaring it
	for out, items in model.files.items():
		for i, item in enumerate(items):
			if item[0] == "enum":
				for c in item[3]:
					item_of.setdefault(c, (out, i))

	def add(te, anchor, named=False):
		for m in [model, *model.bases]:
			if te.name in m.typed or (te.name in m.type_names and not (named and m is model)):
				raise GenError(f"type {te.name} is declared twice")
			for other in [te.element, *te.enums]:
				if other in m.type_names:
					raise GenError(f"type {other} of {te.name} is declared twice")
		model.type_names.update(n for n in [te.element, *te.enums] if n)
		for c in te.consts:
			if c in model.typed_consts:
				raise GenError(f"{c} belongs to both {model.typed_consts[c].name} and {te.name}")
			model.typed_consts[c] = te
		model.typed[te.name] = te
		model.type_names.add(te.name)
		model.anchored[anchor].append(te)

	# Named C enums, and anonymous enums with an integer typedef right after them.
	for out, items in model.files.items():
		for i, item in enumerate(items):
			if item[0] != "enum":
				continue
			_, node, name, consts = item
			if name is None:
				nxt = items[i + 1] if i + 1 < len(items) else None
				if nxt is None or nxt[0] != "typedef" or nxt[1] in TABLE.RAW_PAIRS or int_type(model, nxt[2]) is None:
					continue
				name = nxt[1]
				backing = int_type(model, nxt[2])
				model.pair_names.add(name)
			elif name in TABLE.BACKINGS:
				backing = TABLE.BACKINGS[name]
			else:
				fixed = node.get("fixedUnderlyingType")
				backing = int_type(model, parse_type(fixed["qualType"])) if fixed else enum_backing([values[c] for c in consts if c in values])
			kind = "bit_field" if name in TABLE.BIT_FIELDS else TABLE.NAMED_KINDS.get(name, ("enum",))[0]
			te = TypedEnum(name, kind, [c for c in consts if c in values])
			prefix = TABLE.PREFIXES.get(name) or shared_prefix(te.consts)
			if kind == "bit_field":
				plan_bit_field(model, te, TABLE.BIT_FIELDS[name], names, values)
				if INT_BITS[te.backing] != INT_BITS.get(backing):
					raise GenError(f"bit_field {name} is {te.backing}, but {backing} in C")
				te.untyped = [c for c in te.consts if c not in te.typed and c not in te.dropped]
			elif kind == "bit_set":
				te.backing = unsigned(backing)
				te.element = TABLE.NAMED_KINDS[name][1]
				plan_bit_set(te, prefix, values)
			else:
				te.backing = backing
				plan_enum(te, prefix)
				check_range(te, values)
			add(te, (out, i), named=True)

	# New types from table.py. Each takes the width of the slots it types, or 32 bits.
	matches = match_slots(model)
	widths = defaultdict(set)
	for _, _, _, t, typ, _ in matches:
		if c_typed(model, t) is None and int_type(model, t):
			widths[typ].add(INT_BITS.get(int_type(model, t)))
	in_bit_fields = {f[1] for bf in TABLE.BIT_FIELDS.values() for f in bf["fields"]}
	for name, (kind, spec) in TABLE.NEW_TYPES.items():
		consts = table_members(spec, names)
		if not consts:
			continue
		if not isinstance(spec, str):
			for pattern in spec:
				if not pattern.startswith("!") and "*" not in pattern and pattern not in consts:
					raise GenError(f"type {name}: no constant {pattern}")
		te = TypedEnum(name, kind, consts)
		prefix = shared_prefix(consts) if len(consts) > 1 else spec if isinstance(spec, str) else ""
		if not prefix:
			raise GenError(f"type {name}: its members share no prefix")
		if len(widths[name]) > 1 or None in widths[name]:
			raise GenError(f"type {name} types slots of different or ABI-dependent widths")
		bits = next(iter(widths[name]), 32)
		if kind == "bit_set":
			te.backing = f"u{bits}"
			te.element = element_name(name)
			plan_bit_set(te, prefix, values)
		else:
			# A field of a signed enum is sign-extended, so an enum in a bit_field is unsigned.
			te.backing = f"u{bits}" if name in in_bit_fields else f"i{bits}"
			plan_enum(te, prefix)
			check_range(te, values)
		anchor = next((item_of[c] for c in consts if c in item_of), (model.const_sources[consts[0]][0], "macros"))
		add(te, anchor)

	# bit_fields that are no C enum: emitted with their first constant, or after the first field enum.
	for name, bf in TABLE.BIT_FIELDS.items():
		if find_typed(model, name):
			continue
		consts = table_members(bf["constants"], names) if bf["constants"] else []
		after = next((model.typed[f[1]] for f in bf["fields"] if f[1] in model.typed), None)
		if not consts and after is None:
			continue
		te = TypedEnum(name, "bit_field", consts)
		plan_bit_field(model, te, bf, names, values)
		anchor = item_of[consts[0]] if consts else next(k for k, tes in model.anchored.items() if after in tes)
		add(te, anchor)

	plan_slots(model, matches)


def enum_backing(vals):
	if all(-2**31 <= v < 2**31 for v in vals):
		return "c.int"
	if all(0 <= v < 2**32 for v in vals):
		return "c.uint"
	return "i64"


def check_range(te, values):
	bits = INT_BITS.get(te.backing)
	if bits is None:
		return
	low, high = (0, 2**bits) if te.backing.startswith(("u", "c.u")) else (-2**(bits-1), 2**(bits-1))
	wide = [c for c in te.consts if not low <= values[c] < high]
	if wide:
		raise GenError(f"type {te.name} ({te.backing}) cannot hold {', '.join(wide)}")


def plan_enum(te, prefix):
	for c in te.consts:
		te.members[c] = member_name(te.name, c[len(prefix):] if c.startswith(prefix) else c)
	if len(set(te.members.values())) != len(te.members):
		raise GenError(f"type {te.name}: members collide once {prefix} is dropped")


def plan_bit_set(te, prefix, values):
	"""Single bits become elements. The rest, or every constant of a type in ELEMENTS, become typed constants."""
	mask = (1 << INT_BITS[te.backing]) - 1
	if te.name in TABLE.ELEMENTS:
		te.bits = dict(TABLE.ELEMENTS[te.name])
		te.typed = list(te.consts)
	else:
		for c in te.consts:
			v = values[c] & mask
			if v != 0 and v & (v - 1) == 0:
				element = member_name(te.element, c[len(prefix):] if c.startswith(prefix) else c)
				te.members[c] = element
				te.bits.setdefault(element, v.bit_length() - 1)
		te.typed = [c for c in te.consts if c not in te.members]
	by_bit = {}
	for element, bit in te.bits.items():
		by_bit.setdefault(bit, element)
	for c in te.typed:
		v = values[c] & mask
		set_bits = [b for b in range(INT_BITS[te.backing]) if v >> b & 1]
		if all(b in by_bit for b in set_bits):
			te.literals[c] = "{" + ", ".join(f".{by_bit[b]}" for b in set_bits) + "}"
		else:
			te.literals[c] = None  # bits no element names: emitted with transmute


def plan_bit_field(model, te, bf, names, values):
	width = INT_BITS[bf["backing"]]
	te.backing = bf["backing"]
	for ename, spec in bf["enums"].items():
		if isinstance(spec, dict):
			te.enums[ename] = dict(spec)
		else:
			consts, shift = table_members(spec[0], names), spec[1]
			prefix = shared_prefix(consts)
			te.enums[ename] = {member_name(ename, c[len(prefix):]): (values[c] & ((1 << width) - 1)) >> shift for c in consts}

	field_members = {}  # field enum -> {value: member}
	offset = 0
	for fname, ftype, bits in bf["fields"]:
		if ftype in te.enums:
			members = te.enums[ftype]
		elif ftype in ("bool", "_") or ftype in INT_BITS:
			members = None
		else:
			other = find_typed(model, ftype)
			if other is None or other.kind != "enum" or not other.backing.startswith("u"):
				raise GenError(f"bit_field {te.name}: field {fname} needs an unsigned enum, not {ftype}")
			members = {other.members[c]: values[c] for c in other.consts}
		if members is not None:
			too_big = [m for m, v in members.items() if not 0 <= v < 1 << bits]
			if too_big:
				raise GenError(f"bit_field {te.name}: {ftype} does not fit {bits} bits: {', '.join(too_big)}")
			field_members[ftype] = {}
			for m, v in members.items():
				field_members[ftype].setdefault(v, m)
		te.fields.append((fname, ftype, bits, offset))
		offset += bits
	if offset != width:
		raise GenError(f"bit_field {te.name}: fields take {offset} bits, {te.backing} has {width}")

	te.typed = table_members(bf["constants"], te.consts or names) if bf["constants"] else []
	te.dropped = table_members(bf.get("drop", []), te.consts) if bf.get("drop") else []
	if not te.consts:
		te.consts = list(te.typed)
	for c in te.typed:
		u = values[c] & ((1 << width) - 1)
		parts = []
		for fname, ftype, bits, off in te.fields:
			x = (u >> off) & ((1 << bits) - 1)
			if x == 0:
				continue
			if ftype == "_":
				raise GenError(f"bit_field {te.name}: {c} sets padding bits")
			if ftype == "bool":
				parts.append(f"{fname} = true")
			elif ftype in field_members:
				if x in field_members[ftype]:
					parts.append(f"{fname} = .{field_members[ftype][x]}")
				elif x == (1 << bits) - 1:
					# A mask: every bit of the field, which no member names.
					parts.append(f"{fname} = {ftype}({x:#x})")
				else:
					raise GenError(f"bit_field {te.name}: {c} has no {ftype} member for {x}")
			else:
				parts.append(f"{fname} = {x:#x}")
		te.literals[c] = "{" + ", ".join(parts) + "}"


def match_slots(model):
	"""
	The function parameters and results, callback parameters and record fields that table.py rules name:
	[(rule, owner, key, C type, type, is a pointer)]. key is a parameter index, "return" or the field.
	"""
	slots = []  # (owner, key, name, C type, is field)
	for items in model.files.values():
		for item in items:
			if item[0] == "func":
				node = item[1]
				ftype = parse_type(node["type"]["qualType"])
				pnames = [p.get("name") for p in node.get("inner", []) if p.get("kind") == "ParmVarDecl"]
				slots.append((node["name"], "return", None, ftype[1], False))
				slots += [(node["name"], i, pnames[i] if i < len(pnames) else None, p, False) for i, p in enumerate(ftype[2])]
			elif item[0] == "typedef":
				_, name, t, node, header = item
				ft = strip_const(t)
				if ft[0] == "ptr":
					ft = strip_const(ft[1])
				if ft[0] != "func":
					continue
				pnames = source_param_names(model, node, header, t) or []
				slots.append((name, "return", None, ft[1], False))
				slots += [(name, i, pnames[i] if i < len(pnames) else None, p, False) for i, p in enumerate(ft[2])]
			elif item[0] == "record":
				rec = item[1]
				slots += [(rec.name, f, f, ft, True) for f, ft, nested, _ in rec.fields if f and nested is None]

	def owner_matches(owner, field, is_field, owners):
		if isinstance(owners, list):
			return not is_field and table_members(owners, [owner]) == [owner]
		for o in owners if isinstance(owners, tuple) else (owners,):
			if o == (f"{owner}.{field}" if is_field else owner):
				return True
		return False

	def key_matches(key, name, t, is_field, want):
		for w in want if isinstance(want, tuple) else (want,):
			if (w == "result" and key == "return") or (w == "field" and is_field):
				return True
			if isinstance(key, int) and not is_field and (w == "*" or w == name):
				return True
		return False

	for owner, key, name, t, is_field in slots:
		te = c_typed(model, t)
		if te is not None and te.name in TABLE.BACKINGS:
			raise GenError(f"{owner} {key} is a {te.name}, whose backing differs from C's")

	matches = []
	for i, (owners, want, typ) in enumerate(TABLE.SLOTS):
		for owner, key, name, t, is_field in slots:
			if owner_matches(owner, key, is_field, owners) and key_matches(key, name, t, is_field, want):
				matches.append((("slot", i), owner, key, t, typ, False))
	for i, (owner, param, typ) in enumerate(TABLE.POINTER_SLOTS):
		for o, key, name, t, is_field in slots:
			if o == owner and name == param and not is_field:
				if strip_const(t)[0] != "ptr":
					raise GenError(f"{owner}({param}) is not a pointer")
				matches.append((("pointer", i), owner, key, strip_const(t)[1], typ, True))
	return matches


def plan_slots(model, matches):
	"""Give each matched integer slot its type, if the type fits it exactly."""
	for hit, owner, key, t, typ, pointer in matches:
		have = c_typed(model, t)
		if have is not None:
			if have.name != typ:
				raise GenError(f"{owner} {key} is {have.name} in C, not {typ}")
			RULE_HITS[hit] += 1
			continue
		it = int_type(model, t)
		if it is None:
			continue
		te = find_typed(model, typ)
		if te is None:
			raise GenError(f"{owner} {key}: unknown type {typ}")
		if INT_BITS.get(it) is None or INT_BITS.get(it) != INT_BITS.get(te.backing):
			raise GenError(f"{owner} {key} is {it}, which {typ} ({te.backing}) does not fit exactly")
		spec = ("ptr" if pointer else "named", typ)
		if model.slot_types[owner].get(key, spec) != spec:
			raise GenError(f"{owner} {key} is typed twice")
		model.slot_types[owner][key] = spec
		RULE_HITS[hit] += 1


def check_table(models):
	"""Every entry of table.py must be used, once every target is planned."""
	typed = {n for m in models for n in m.typed}
	unused = [f"NEW_TYPES {n}" for n in TABLE.NEW_TYPES if n not in typed]
	unused += [f"BIT_FIELDS {n}" for n in TABLE.BIT_FIELDS if n not in typed]
	unused += [f"{what} {n}" for what, table in (("NAMED_KINDS", TABLE.NAMED_KINDS), ("ELEMENTS", TABLE.ELEMENTS),
		("PREFIXES", TABLE.PREFIXES), ("NUMBER_KEYS", TABLE.NUMBER_KEYS)) for n in table if n not in typed]
	unused += [f"RAW_PAIRS {n}" for n in TABLE.RAW_PAIRS if not any(n in m.typedefs for m in models)]
	unused += [f"SLOTS rule {i+1} ({rule[0]})" for i, rule in enumerate(TABLE.SLOTS) if not RULE_HITS[("slot", i)]]
	unused += [f"POINTER_SLOTS {o}({p})" for i, (o, p, _) in enumerate(TABLE.POINTER_SLOTS) if not RULE_HITS[("pointer", i)]]
	if unused:
		raise GenError("table.py entries that match nothing:\n\t" + "\n\t".join(unused))


